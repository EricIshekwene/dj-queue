@testable import DJQCore

/// Milestone-3 proof on REAL clips (read-only sources). Run with `scripts/render-proof.sh`
/// (sets DJQ_PROOF=1, DJQ_ROOT=dev root, DJQ_HOME=render-home, DJQ_EVIDENCE=evidence dir).
@Suite(.serialized) struct RenderProofTests {
  static var env: [String: String] { ProcessInfo.processInfo.environment }

  struct Case {
    var tag: String
    var cropX: Double  // left edge of a full-height 9:16 crop in 4K pixels
    var text: String
    var source: String  // audio source, for the report
  }

  @Test(.enabled(if: env["DJQ_PROOF"] == "1"), .timeLimit(.minutes(10)))
  func milestone3Proof() throws {
    let evidence = URL(fileURLWithPath: Self.env["DJQ_EVIDENCE"] ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("code/dj-queue-dev/evidence/render").path)
    try FileManager.default.createDirectory(at: evidence, withIntermediateDirectories: true)
    let paths = Paths.standard
    #expect(!paths.root.path.hasPrefix(FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Movies").path),
            "proof must run against the dev root")
    let store = try Store(paths: paths)
    let intake = try Intake(store: store).run()
    let renderer = Renderer(store: store, outputRoot: evidence)
    try renderer.deleteRenders(except: [])  // fresh renders so the timings are real

    let cases = [
      Case(tag: "Amarider", cropX: 1342, text: "Amarider 🔥", source: "rekordbox"),
      Case(tag: "yayo x johnny", cropX: 1492, text: "Yayo x Johnny 🔥", source: "camera"),
    ]
    var md = """
    # Milestone 3 proof — render engine (preview == export, −14 LUFS)

    Generated by `scripts/render-proof.sh` (test `RenderProofTests.milestone3Proof`) on \(ISO8601DateFormatter().string(from: Date())).
    Sources are the real Afroween clips via the dev root symlinks (read-only). Intake: \(intake.sessionsSeen) session(s).
    Renders: `h264_videotoolbox` High 12 Mb/s, 1080×1920, AAC 256k 48 kHz, two-pass `loudnorm` I=−14 TP=−1 LRA=11 linear.

    """
    var loudRows: [String] = []
    var diffRows: [String] = []
    var files: [String] = []
    var coverRows: [String] = []

    for c in cases {
      let v = try #require(try store.videos().first { $0.tag == c.tag && $0.type == .short }, "video \(c.tag)")
      let src = try #require(try store.fileURL(for: v))
      let info = try Media.probe(src)
      var e = try store.edit(videoId: v.id)
      e.aspect = .r9x16
      e.crop = CropRect(x: c.cropX, y: 0, w: 2160 * 9 / 16, h: 2160)
      e.trimIn = v.markerIn ?? 3
      e.trimOut = v.markerOut ?? info.duration
      e.coverTime = nil
      e.coverIncludesText = true
      try store.save(e, videoId: v.id)
      var ver = try store.versions(videoId: v.id).first { $0.number == 1 } ?? Version(number: 1)
      ver.text = c.text; ver.noText = false; ver.style = .box; ver.size = 64; ver.posX = 0.5; ver.posY = 0.5
      ver.align = .center; ver.textStart = nil; ver.textEnd = nil
      if ver.caption?.isEmpty ?? true { ver.caption = "proof" }
      try store.save(ver, videoId: v.id)
      let rv = try #require(try store.resolvedVersion(videoId: v.id, number: 1))

      let t0 = Date()
      let r = try renderer.ensureRender(videoId: v.id, versionNo: 1, platform: nil)
      let secs = Date().timeIntervalSince(t0)
      let out = URL(fileURLWithPath: try #require(r.outputPath))
      let trim = e.trim(duration: v.duration)
      let probe = try Media.probe(out)

      // (a) Loudness: source segment (pass-1 loudnorm), full source file and output (ebur128 peak=true).
      let srcFull = try Renderer.measureLoudness(src)
      let outL = try Renderer.measureLoudness(out)
      let l = try #require(r.loudness)
      #expect(abs(outL.inputI - -14) <= 0.5, "\(c.tag) integrated \(outL.inputI)")
      #expect(outL.inputTP <= -0.9, "\(c.tag) true peak \(outL.inputTP)")
      loudRows.append(String(format: "| %@ (%@) | %.1f / %.1f dBTP | %.1f / %.1f dBTP / LRA %.1f | **%.1f** / **%.1f dBTP** / LRA %.1f | %.1f s for %.1f s (%.1f× realtime) |",
                             c.tag, c.source, srcFull.inputI, srcFull.inputTP, l.inputI, l.inputTP, l.inputLRA,
                             outL.inputI, outL.inputTP, outL.inputLRA, secs, trim.duration, trim.duration / secs))

      // (b) Preview == export at two times.
      let overlay = try #require(TextOverlay.image(for: rv, aspect: .r9x16))
      let box = try #require(TextOverlay.textBounds(for: rv, aspect: .r9x16))
      let fd = 1001.0 / 30000
      for k in [60, 300] {
        let t = (Double(k) + 0.5) * fd
        let sourceFrame = try #require(Media.frame(src, at: trim.start + t, maxSize: .zero))
        let preview = try #require(Media.compose(sourceFrame, crop: e.crop, aspect: .r9x16,
                                                 size: CGSize(width: 1080, height: 1920), overlay: overlay))
        let export = try #require(Media.frame(out, at: t, maxSize: .zero))
        let all = meanAbsDiff(preview, export), inBox = meanAbsDiff(preview, export, in: box)
        let p = psnr(preview, export)
        // Same comparison with ffmpeg as the decoder for both sides (independent of AVFoundation).
        let ffSrc = ffmpegFrame(src, at: trim.start + t, dir: evidence)
        let ffOut = ffmpegFrame(out, at: t, dir: evidence)
        let ffPreview = ffSrc.flatMap { Media.compose($0, crop: e.crop, aspect: .r9x16,
                                                         size: CGSize(width: 1080, height: 1920), overlay: overlay) }
        let ffExport = ffOut.flatMap { Media.compose($0, crop: CropRect(x: 0, y: 0, w: 1080, h: 1920), aspect: .r9x16,
                                                        size: CGSize(width: 1080, height: 1920)) }
        var ffAll = Double.nan, ffBox = Double.nan, decoderGap = Double.nan
        if let ffPreview, let ffExport {
          ffAll = meanAbsDiff(ffPreview, ffExport); ffBox = meanAbsDiff(ffPreview, ffExport, in: box)
          decoderGap = meanAbsDiff(export, ffExport)
        }
        #expect(inBox < 4, "\(c.tag) t=\(t) text-box diff \(inBox)")
        #expect(all < 8, "\(c.tag) t=\(t) overall diff \(all)")
        let name = "\(c.tag.replacingOccurrences(of: " ", with: "-"))-t\(String(format: "%.2f", t))-preview-export-diff.png"
        try Media.writePNG(sideBySide(preview, export), to: evidence.appendingPathComponent(name))
        files.append(name)
        #expect(ffBox < 4 && ffAll < 8, "\(c.tag) t=\(t) ffmpeg-decoded diff \(ffAll) / \(ffBox)")
        diffRows.append(String(format: "| %@ | %.3f s (frame %d) | %.2f | %.2f | %.1f dB | %.2f / %.2f | %.1f | `%@` |",
                               c.tag, t, k, all, inBox, p, ffAll, ffBox, decoderGap, name))
      }
      files.append(out.lastPathComponent)
      if let cp = r.coverPath {
        files.append(URL(fileURLWithPath: cp).lastPathComponent)
        // Cover == preview of the trim's first frame (JPEG noise only).
        let coverImg = try #require(loadImage(URL(fileURLWithPath: cp)))
        let first = try #require(Media.frame(src, at: trim.start, maxSize: .zero))
        let firstPreview = try #require(Media.compose(first, crop: e.crop, aspect: .r9x16,
                                                      size: CGSize(width: 1080, height: 1920), overlay: overlay))
        let cd = meanAbsDiff(firstPreview, Media.compose(coverImg, crop: CropRect(x: 0, y: 0, w: 1080, h: 1920),
                                                         aspect: .r9x16, size: CGSize(width: 1080, height: 1920))!)
        #expect(cd < 3, "\(c.tag) cover diff \(cd)")
        coverRows.append(String(format: "| %@ | `%@` | %.2f |", c.tag, URL(fileURLWithPath: cp).lastPathComponent, cd))
      }
      try TextOverlay.write(for: rv, aspect: .r9x16, to: evidence.appendingPathComponent("\(c.tag.replacingOccurrences(of: " ", with: "-"))-overlay.png"))
      files.append("\(c.tag.replacingOccurrences(of: " ", with: "-"))-overlay.png")
      md += String(format: "\n- **%@**: `%@` — %d×%d %@ %.2f fps, %.3f s (trim %.3f–%.3f = %.3f s), %.1f MB, crop x=%.0f w=1215 h=2160\n",
                   c.tag, out.lastPathComponent, probe.width, probe.height, probe.videoCodec, probe.fps, probe.duration,
                   trim.start, trim.end, trim.duration, Double(probe.size) / 1e6, c.cropX)
    }

    md += """

    ## (a) Loudness — target −14 LUFS integrated (±0.5), true peak ≤ −1.0 dBTP

    | Clip (audio) | Source file I / TP (ebur128) | Trimmed source I / TP / LRA (loudnorm pass 1) | Output I / TP / LRA (ebur128) | Render time |
    |---|---|---|---|---|
    \(loudRows.joined(separator: "\n"))

    ## (b) Preview == export

    Preview built exactly as the editor will: `Media.frame(source, trimIn + t)` (AVFoundation, zero tolerance) →
    `Media.compose` (same even-pixel crop as the renderer, scaled to 1080×1920) → `TextOverlay.image` composited with
    Core Graphics. Export: `Media.frame(render.mp4, t)`. Mean absolute difference per 8-bit channel (0–255);
    "text box" = `TextOverlay.textBounds`. The "ffmpeg" column repeats the comparison with ffmpeg decoding both the
    source and the export. "Decoder gap" is AVFoundation vs ffmpeg decoding the *same* export frame: AVFoundation
    colour-manages BT.709 → sRGB (lifted shadows), ffmpeg does not — that is a player difference, not a render
    difference, which is why each comparison uses one decoder for both sides.
    Side-by-side PNGs: preview | export | |diff|×8.

    | Clip | t | MAD overall | MAD in text box | PSNR | ffmpeg MAD overall / box | Decoder gap | File |
    |---|---|---|---|---|---|---|---|
    \(diffRows.joined(separator: "\n"))

    ## Cover

    Cover JPG vs the preview of the trim's first frame (same pipeline, JPEG q 0.92):

    | Clip | Cover | MAD |
    |---|---|---|
    \(coverRows.joined(separator: "\n"))

    ## Files

    \(files.map { "- `\($0)`" }.joined(separator: "\n"))
    """
    try md.write(to: evidence.appendingPathComponent("PROOF.md"), atomically: true, encoding: .utf8)
  }

  /// Full-resolution PNG decoded by ffmpeg (no colour management).
  func ffmpegFrame(_ url: URL, at t: Double, dir: URL) -> CGImage? {
    let png = dir.appendingPathComponent(".grab-\(UUID().uuidString).png")
    defer { try? FileManager.default.removeItem(at: png) }
    guard let r = try? Proc.run(Tools.ffmpeg!, ["-v", "error", "-y", "-ss", String(format: "%.4f", t), "-i", url.path,
                                                "-frames:v", "1", "-update", "1", png.path]), r.status == 0 else { return nil }
    return loadImage(png)
  }

  func psnr(_ a: CGImage, _ b: CGImage) -> Double {
    let pa = Pixels(a), pb = Pixels(b)
    var se = 0.0, n = 0.0
    for i in stride(from: 0, to: pa.data.count, by: 4) {
      for c in 0..<3 { let d = Double(pa.data[i + c]) - Double(pb.data[i + c]); se += d * d; n += 1 }
    }
    return 10 * log10(255 * 255 / max(1e-9, se / n))
  }

  /// preview | export | |diff|×8, each 540×960.
  func sideBySide(_ a: CGImage, _ b: CGImage) -> CGImage {
    let pa = Pixels(a), pb = Pixels(b)
    var diff = [UInt8](repeating: 255, count: pa.data.count)
    for i in stride(from: 0, to: pa.data.count, by: 4) {
      for c in 0..<3 { diff[i + c] = UInt8(min(255, abs(Int(pa.data[i + c]) - Int(pb.data[i + c])) * 8)) }
    }
    let cs = CGColorSpace(name: CGColorSpace.sRGB)!
    let dctx = CGContext(data: &diff, width: pa.w, height: pa.h, bitsPerComponent: 8, bytesPerRow: pa.w * 4, space: cs,
                         bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    let d = dctx.makeImage()!
    let ctx = CGContext(data: nil, width: 1620, height: 960, bitsPerComponent: 8, bytesPerRow: 1620 * 4, space: cs,
                        bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    ctx.interpolationQuality = .high
    for (i, img) in [a, b, d].enumerated() { ctx.draw(img, in: CGRect(x: i * 540, y: 0, width: 540, height: 960)) }
    return ctx.makeImage()!
  }
}
